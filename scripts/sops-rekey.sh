#!/usr/bin/env bash
set -euo pipefail
shopt -s nullglob globstar

user_keys=(keys/aly_*.pub)
host_keys=(keys/root_*.pub)
# Regular-user SSH keys, including Morgan's, do not grant secret access.

if ((${#user_keys[@]} == 0)); then
  echo 'Add an administrator public key to keys/ before generating SOPS rules.' >&2
  exit 1
fi
if [[ ! -s keys/flux_k8s.pub ]]; then
  echo 'Create a Kanto-specific Flux age identity and save its recipient in keys/flux_k8s.pub.' >&2
  exit 1
fi

temporary=$(mktemp)
trap 'rm -f "$temporary"' EXIT
{
  printf '# Auto-generated by just sops-rekey from administrator and host keys.\nkeys:\n'
  for key in "${user_keys[@]}" "${host_keys[@]}"; do
    name=$(basename "$key" .pub)
    if [[ ! $name =~ ^[a-zA-Z0-9_]+$ ]]; then
      echo "Unsupported public key filename: $key" >&2
      exit 1
    fi
    printf '  - &%s %s\n' "$name" "$(ssh-to-age -i "$key")"
  done
  printf '  - &flux_k8s %s\n\ncreation_rules:\n' "$(cat keys/flux_k8s.pub)"
  for path_regex in '^secrets/.*\.ya?ml$' '^k8s/secrets/.*\.ya?ml$'; do
    printf '  - path_regex: %s\n    key_groups:\n      - age:\n' "$path_regex"
    for key in "${user_keys[@]}" "${host_keys[@]}"; do
      printf '          - *%s\n' "$(basename "$key" .pub)"
    done
    if [[ $path_regex == '^k8s/'* ]]; then
      printf '          - *flux_k8s\n'
    fi
  done
} >"$temporary"
mv "$temporary" .sops.yaml

for secret in secrets/**/*.yaml secrets/**/*.yml k8s/secrets/**/*.yaml k8s/secrets/**/*.yml; do
  if [[ "$(sops filestatus "$secret")" == *'"encrypted":true'* ]]; then
    sops updatekeys -y "$secret"
  fi
done
